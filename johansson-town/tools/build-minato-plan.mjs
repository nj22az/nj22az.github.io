import {readFile,writeFile} from 'node:fs/promises';
const source=new URL('../art/izakaya/compact/plan.json',import.meta.url);
const destination=new URL('../src/world/interiors/minato-compact-plan.js',import.meta.url);
const plan=JSON.parse(await readFile(source,'utf8'));
await writeFile(destination,'// Generated by tools/build-minato-plan.mjs from art/izakaya/compact/plan.json.\n// Edit the measured plan, then regenerate; Blender reads the same source.\nexport const MINATO_COMPACT = Object.freeze('+JSON.stringify(plan,null,2)+');\n');
console.log('Wrote compact Minato plan');
