"""Blender-authored long side-part waves for Thao and the shared Creator.
Original low-poly sculpture, head-radius coordinates; no photo geometry copied.
"""
import bpy,math,json
from pathlib import Path
from mathutils import Vector
root=Path(__file__).resolve().parents[2];out=root/'assets/models/wardrobe/ribbon-dress'
bpy.ops.object.select_all(action='SELECT');bpy.ops.object.delete(use_global=False)
parts=[]
def mesh(name,verts,faces,kind='head',shade=1,colour=None):
 m=bpy.data.meshes.new(name);m.from_pydata(verts,[],faces);m.update();m.calc_loop_triangles()
 o=bpy.data.objects.new(name,m);bpy.context.collection.objects.link(o)
 for p in m.polygons:p.use_smooth=True
 parts.append(dict(name=name,kind=kind,shade=shade,colour=colour,vertices=[[round(c,6) for c in v] for v in verts],indices=[i for t in m.loop_triangles for i in t.vertices]))
 return o
# Explicit hairline leaves forehead and eyes clear; asymmetric swept part.
v=[];f=[];cols=48;rows=14
for j in range(rows+1):
 for i in range(cols+1):
  a=i/cols*math.tau;front=max(0,math.cos(a));back=max(0,-math.cos(a))
  hairline=-.08-.48*back+front*(.65+.10*math.sin(a)+.12*math.exp(-((math.sin(a)+.25)/.15)**2))
  theta=.008+(math.acos(hairline)-.008)*j/rows;r=1.075+.014*math.cos(a*12)*math.sin(theta)**2
  v.append((r*math.sin(theta)*math.sin(a),r*math.cos(theta),r*.985*math.sin(theta)*math.cos(a)))
for j in range(rows):
 for i in range(cols):
  a=j*(cols+1)+i;b=a+1;c=a+cols+1;d=c+1;f.extend([(a,c,b),(b,c,d)])
mesh('Side-part crown and shaped hairline',v,f)
# Back curtain: continuous volume, gentle wave rhythm and feathered tips.
v=[];f=[];cols=40;rows=22
for layer in [0,1]:
 for j in range(rows+1):
  t=j/rows
  for i in range(cols+1):
   a=.91+(math.tau-1.82)*i/cols
   taper=1-.17*t**3
   wave=.055*math.sin(t*math.pi*3.1+a*3)*t+.022*math.cos(a*14)*math.sin(t*math.pi/2)
   rad=(1.045+wave)*taper-layer*.11
   y=-.05-2.22*t+.065*math.cos(a*10)*t**5
   x=math.sin(a)*rad;z=math.cos(a)*rad-.03-.08*t
   v.append((x,y,z))
stride=(cols+1)*(rows+1)
for layer in [0,1]:
 for j in range(rows):
  for i in range(cols):
   a=layer*stride+j*(cols+1)+i;b=a+1;c=a+cols+1;d=c+1
   f.append((a,c,d,b) if layer==0 else (a,b,d,c))
for j in range(rows):
 for i in [0,cols]:
  a=j*(cols+1)+i;b=a+cols+1;f.append((a,a+stride,b+stride,b))
for i in range(cols):
 a=rows*(cols+1)+i;f.append((a,a+1,a+1+stride,a+stride))
mesh('Continuous soft-wave back curtain',v,f,'tail')
# Front tresses have broad S curves, flat oval sections and tapered ends.
def tress(side,offset,phase):
 verts=[];faces=[];n=28;circ=8
 for j in range(n+1):
  t=j/n;y=.48-2.62*t
  cx=side*(.84+.12*min(1,t*5)+offset+.14*math.sin(t*math.pi*2.5+phase)*math.sin(t*math.pi/2))
  cz=.25+.49*math.sin(t*math.pi/2)+.065*math.sin(t*math.pi*3+phase)
  root=min(1,.04+t*7);width=(.16 if offset==0 else .12)*root*(1-.95*t**5);depth=.10*root*(1-.92*t**4)
  for i in range(circ):
   a=i/circ*math.tau;verts.append((cx+width*math.cos(a),y,cz+depth*math.sin(a)))
 for j in range(n):
  for i in range(circ):
   a=j*circ+i;b=j*circ+(i+1)%circ;c=a+circ;d=b+circ;faces.extend([(a,c,b),(b,c,d)])
 faces.append(tuple(reversed(range(circ))));faces.append(tuple(n*circ+i for i in range(circ)))
 mesh('Face-framing S wave %s %s'%(side,offset),verts,faces,'tail',1.025 if offset==0 else .96)
for side in [-1,1]:
 tress(side,0,0 if side==1 else .6);tress(side,.095,1.3)
# Scalp part, on the crown rather than a line through the entire head.
v=[];f=[]
for i in range(25):
 t=i/24;x=-.24-.02*t;y=.70+.36*t
 for dx in [-.0035,.0035]:v.append((x+dx,y,math.sqrt(max(.002,1.075**2-(x+dx)**2-y*y))+.005))
for i in range(24):a=i*2;f.append((a,a+2,a+3,a+1))
mesh('Narrow natural side part',v,f,'head',.55,'scalp')
# Swept locks bridge crown to sides without a straight fringe.
for k in range(3):
 v=[];f=[]
 for i in range(29):
  t=i/28;x=-.24+1.11*t;y=.83-.43*t+.14*math.sin(math.pi*t)+k*.052
  for q in [-1,1]:
   yy=y+q*.036*math.sin(math.pi*(.05+.9*t));z=math.sqrt(max(.025,1.10**2-x*x-yy*yy))+.018
   v.append((x,yy,z))
 for i in range(28):a=i*2;f.append((a,a+2,a+3,a+1))
 mesh('Soft swept crown ridge '+str(k+1),v,f,'head',1.02+k*.018)
(root/'src/avatars/sidepart-waves-data.js').write_text('// Generated by tools/blender/build-sidepart-waves.py in Blender.\nexport const SIDEPART_WAVES = '+json.dumps(parts,separators=(',',':'))+';\n')
for o in bpy.context.scene.objects:
 mat=bpy.data.materials.new(o.name);mat.diffuse_color=(.028,.021,.019,1);o.data.materials.append(mat)
bpy.ops.wm.save_as_mainfile(filepath=str(out/'sidepart-waves.blend'),compress=True)
print('WAVES_EXPORTED',sum(len(p['indices'])//3 for p in parts))
