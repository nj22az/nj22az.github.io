import {readFile,readdir,writeFile,mkdir} from 'node:fs/promises';
import {resolve,relative} from 'node:path';
import {createHash} from 'node:crypto';
import {pathToFileURL} from 'node:url';

export async function buildOffline(root){
 const selected=new Set(['index.html','manifest.webmanifest','pwa.js','title-sky.js','resident-guide.js','landing.js','loading-progress.js','loading-facts.js','offline/ui.js','offline/ui.css','offline/worker.js']);
 async function walk(directory){for(const entry of await readdir(resolve(root,directory),{withFileTypes:true})){const path=directory+'/'+entry.name;if(entry.name==='source'||/\.blend\d?$|\.py$/.test(entry.name))continue;if(entry.isDirectory())await walk(path);else selected.add(path);}}
 // All seasons, rooms, residents, audio, papers and catalogues; no docs, authoring sources or personal saves.
 await walk('assets');
 const runtime=JSON.parse(await readFile(resolve(root,'runtime/.vite/manifest.json'),'utf8'));
 for(const entry of Object.values(runtime))for(const path of [entry.file,...(entry.css||[]),...(entry.assets||[])])selected.add('runtime/'+path);
 const html=await readFile(resolve(root,'index.html'),'utf8');
 for(const [,path] of html.matchAll(/<link[^>]+href="\.\/([^"?]+\.css)(?:\?[^"]*)?"/g))selected.add(path);
 const files=[];
 for(const path of [...selected].sort()){
  const absolute=resolve(root,path);if(!relative(root,absolute)||relative(root,absolute).startsWith('..'))throw Error('Offline file escaped town: '+path);
  const bytes=await readFile(absolute);files.push({url:path,bytes:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex')});
 }
 const manifest={version:createHash('sha256').update(JSON.stringify(files)).digest('hex').slice(0,20),bytes:files.reduce((n,file)=>n+file.bytes,0),files};
 await mkdir(resolve(root,'offline'),{recursive:true});
 await writeFile(resolve(root,'offline/manifest.js'),'/* Generated by npm run build:runtime. */\nglobalThis.TOWN_OFFLINE='+JSON.stringify(manifest)+';\n');
 console.log(`Offline island: ${files.length} files, ${(manifest.bytes/1048576).toFixed(1)} MiB, ${manifest.version}`);
 return manifest;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href)await buildOffline(resolve(new URL('..',import.meta.url).pathname));
