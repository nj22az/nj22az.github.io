#!/usr/bin/env python3
"""Build the homepage stylesheet from its existing CSS modules in cascade order."""

import argparse
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'css/office-portfolio.bundle.css'
HOME_MODULES = (
    'css/office-mascots.css',
    'css/project-explorer.css',
    'css/office-port.css',
    'css/office-home.css',
    'css/office-calendar.css',
    'css/office-blog.css',
    'animation-studio/studio.css',
    'css/site-family.css',
)


def build():
    imports = re.findall(r'@import\s+url\("([^"]+)"\);', (ROOT / 'styles.css').read_text(encoding='utf-8'))
    local_imports = [url.split('?', 1)[0] for url in imports if not url.startswith('https://')]
    sections = ['/* Generated by tools/office-home/build-css.py. Edit the source modules. */']
    for path in (*local_imports, *HOME_MODULES):
        source = (ROOT / path).read_text(encoding='utf-8').strip()
        if '@import' in source:
            raise ValueError(f'Nested @import in {path}')
        sections.append(f'/* {path} */\n{source}')
    return '\n\n'.join(sections) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    css = build()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding='utf-8') != css:
            parser.exit(1, 'Homepage CSS is stale. Run python3 tools/office-home/build-css.py.\n')
        print('Homepage CSS bundle is current.')
    else:
        OUTPUT.write_text(css, encoding='utf-8')
